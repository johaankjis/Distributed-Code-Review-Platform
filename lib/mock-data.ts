// Helper function to populate related data
export function populatePullRequest(pr: PullRequest): PullRequest {
  return {
    ...pr,
    author: mockUsers.find((u) => u.id === pr.author_id),
    repository: mockRepositories.find((r) => r.id === pr.repository_id),
    reviews: mockReviews
      .filter((r) => r.pull_request_id === pr.id)
      .map((review) => ({
        ...review,
        reviewer: mockUsers.find((u) => u.id === review.reviewer_id),
      })),
    assignments: mockAssignments
      .filter((a) => a.pull_request_id === pr.id)
      .map((assignment) => ({
        ...assignment,
        reviewer: mockUsers.find((u) => u.id === assignment.reviewer_id),
        assigned_by: mockUsers.find((u) => u.id === assignment.assigned_by_id),
      })),
    metrics: mockMetrics.find((m) => m.pull_request_id === pr.id),
  }
}

export function getAllPullRequests(): PullRequest[] {
  return mockPullRequests.map(populatePullRequest)
}

export function getPullRequestById(id: string): PullRequest | undefined {
  const pr = mockPullRequests.find((p) => p.id === id)
  return pr ? populatePullRequest(pr) : undefined
}
